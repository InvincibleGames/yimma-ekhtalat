import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const root='http://127.0.0.1:8765/game-007/';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:950},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(root,{waitUntil:'networkidle',timeout:30000});
 assert.match(await page.title(),/يمّه اختلط!/);
 assert.equal(await page.locator('#worldGrid .world').count(),5);
 await fs.promises.mkdir('game-007/qa-screenshots',{recursive:true});
 await page.screenshot({path:'game-007/qa-screenshots/01-menu-desktop.png'});
 const names=['W01_Kitchen','W02_Spice_Market','W03_Sweets','W04_Crafts','W05_Pearl_Coast'];
 const kinds=[['Rice','Lentil','Chickpea','MungBean','KidneyBean'],['Cardamom','Clove','Peppercorn','Coriander','StarAnise'],['PinkSweet','YellowSweet','GreenSweet','Chocolate','CandyBall'],['BlueButton','RedButton','PearlBead','WoodBead'],['Pearl','Shell','SeaGlass','Stone']];
 let paths=[];
 names.forEach((key,i)=>{
  paths.push('assets/'+key+'/background.svg','assets/'+key+'/tray.svg','assets/'+key+'/basket_1.svg');
  kinds[i].forEach(k=>paths.push('assets/'+key+'/item_'+k+'.svg'));
 });
 assert.equal(paths.length,38);
 const checks=await page.evaluate(async paths=>Promise.all(paths.map(async path=>{
  const response=await fetch(path);
  const text=await response.text();
  return {path,status:response.status,svg:text.includes('<svg')};
 })),paths);
 const bad=checks.filter(x=>x.status!==200||!x.svg);
 assert.equal(bad.length,0,'Missing runtime graphics: '+JSON.stringify(bad));
 console.log('PASS: 38/38 runtime SVG assets load');
 await page.locator('#worldGrid [data-world="0"]').click();
 assert.equal(await page.locator('#levelGrid [data-stage]').count(),5);
 await page.screenshot({path:'game-007/qa-screenshots/02-level-select-desktop.png'});
 await page.locator('#levelGrid [data-stage="1"]').click();
 assert.isTrue?.(true);
 assert.equal(await page.locator('#game').isVisible(),true);
 await page.waitForTimeout(650);
 const pixel=await page.locator('#board').evaluate(canvas=>Array.from(canvas.getContext('2d').getImageData(550,250,1,1).data));
 assert.ok(pixel[3]>0,'Canvas not rendered');
 await page.screenshot({path:'game-007/qa-screenshots/03-gameplay-desktop.png'});
 await page.locator('#finishBtn').click();
 assert.equal(await page.locator('#results').isVisible(),true);
 await page.locator('#againBtn').click();
 assert.equal(await page.locator('#game').isVisible(),true);
 console.log('PASS: menu → world → level → game → results → replay');
 const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const mp=await mobile.newPage();
 mp.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mp.goto(root,{waitUntil:'networkidle',timeout:30000});
 assert.equal(await mp.locator('#worldGrid .world').count(),5);
 await mp.screenshot({path:'game-007/qa-screenshots/04-menu-mobile.png',fullPage:true});
 await mp.locator('#worldGrid [data-world="4"]').click();
 assert.equal(await mp.locator('#levelGrid [data-stage]').count(),5);
 await mp.locator('#levelGrid [data-stage="1"]').click();
 await mp.waitForTimeout(650);
 await mp.locator('#board').tap({position:{x:160,y:90}});
 assert.equal(await mp.locator('#game').isVisible(),true);
 await mp.screenshot({path:'game-007/qa-screenshots/05-gameplay-mobile.png',fullPage:true});
 await mobile.close();
 assert.deepEqual(errors,[],'Browser JS errors');
 console.log('PASS: mobile touch + menus + 0 JS errors');
} finally {await browser.close();}
