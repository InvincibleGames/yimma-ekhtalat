import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const BASE='http://127.0.0.1:8977/final/';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const errors=[];
await fs.mkdir('final/evidence',{recursive:true});
try{
 const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push('desktop: '+e.message));
 await page.goto(BASE,{waitUntil:'domcontentloaded',timeout:30000});
 await page.locator('.game-logo h1').waitFor({timeout:12000});
 assert.equal(await page.evaluate(()=>window.YimmaQA.getState().screen),'main');
 assert.equal(await page.locator('.characters').count(),1);
 await page.screenshot({path:'final/evidence/01-main-desktop.png',fullPage:true});
 await page.locator('[data-action="worlds"]').first().click();
 console.log('POST WORLD CLICK',JSON.stringify({state:await page.evaluate(()=>window.YimmaQA.getState()),errors,screen:await page.locator('#screen').innerText()}));
 assert.equal(await page.locator('.world-card').count(),5);
 await page.screenshot({path:'final/evidence/02-worlds-desktop.png',fullPage:true});
 await page.locator('[data-action="world"][data-world="0"]').click();
 assert.equal(await page.locator('.level-node').count(),5);
 assert.equal(await page.locator('.level-node:not(:disabled)').count(),1);
 await page.screenshot({path:'final/evidence/03-levels-desktop.png',fullPage:true});
 await page.locator('[data-action="level"][data-level="1"]').click();
 assert.equal(await page.evaluate(()=>window.YimmaQA.getState().screen),'game');
 if(await page.locator('#pauseOverlay [data-action="tutorialDone"]').count())await page.locator('#pauseOverlay [data-action="tutorialDone"]').click();
 const canvas=page.locator('#gameCanvas');
 await canvas.waitFor();
 await page.waitForTimeout(550);
 let px=await canvas.evaluate(c=>Array.from(c.getContext('2d').getImageData(Math.floor(c.width*.5),Math.floor(c.height*.5),1,1).data));
 assert(px[3]>0,'canvas blank');
 await page.screenshot({path:'final/evidence/04-gameplay-desktop.png',fullPage:true});
 const rect=await canvas.boundingBox();
 await page.mouse.move(rect.x+rect.width*.3,rect.y+rect.height*.38);
 await page.mouse.down();await page.mouse.move(rect.x+rect.width*.48,rect.y+rect.height*.47,{steps:10});await page.mouse.up();
 await page.locator('[data-action="pause"]').click();
 assert(await page.locator('#pauseOverlay').isVisible(),'pause overlay hidden');
 await page.locator('#pauseOverlay [data-action="resume"]').click();
 assert(!(await page.locator('#pauseOverlay').isVisible()),'resume failed');
 await page.evaluate(()=>window.YimmaQA.finish());
 assert.equal(await page.evaluate(()=>window.YimmaQA.getState().screen),'results');
 await page.screenshot({path:'final/evidence/05-results-desktop.png',fullPage:true});
 await page.locator('[data-action="levels"]').click();
 assert.equal(await page.locator('.level-node:not(:disabled)').count(),2);
 await page.locator('[data-action="worlds"]').first().click();
 await page.locator('[data-action="home"]').first().click();
 for(const [name,selector] of [['shop','.shop-item'],['challenges','.challenge'],['achievements','.achievement'],['customize','.shop-item'],['settings','.setting-row'],['tutorial','.tutorial-illustration']]){
  if(name==='settings')await page.locator('#settingsBtn').click();else await page.locator('[data-action="'+name+'"]').first().click();
  assert(await page.locator(selector).count()>0,'screen missing '+name);
  await page.locator('#backBtn').click();
 }
 assert.deepEqual(errors,[],errors.join('\n'));
 const paths=await page.evaluate(()=>window.YimmaQA.assetPaths());
 for(const path of paths){const response=await page.request.get(path);assert.equal(response.status(),200,'missing background '+path)}
 console.log('PASS DESKTOP: all screens, 5 worlds, 25 stage data, actual canvas, pause/results, save/unlock, controls, art');
 await context.close();
 const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,hasMobileTouch:true, reducedMotion:'reduce'});
 const mp=await mobile.newPage();
 mp.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mp.goto(BASE,{waitUntil:'domcontentloaded',timeout:30000});
 assert.equal(await mp.locator('.characters').count(),1);
 await mp.screenshot({path:'final/evidence/06-main-mobile.png',fullPage:true});
 await mp.locator('[data-action="worlds"]').first().click();
 assert.equal(await mp.locator('.world-card').count(),5);
 await mp.screenshot({path:'final/evidence/07-worlds-mobile.png',fullPage:true});
 await mp.locator('[data-action="world"][data-world="4"]').click();
 await mp.locator('[data-action="level"][data-level="1"]').click();
 if(await mp.locator('#pauseOverlay [data-action="tutorialDone"]').count())await mp.locator('#pauseOverlay [data-action="tutorialDone"]').click();
 const mobileCanvas=mp.locator('#gameCanvas');
 const bounds=await mobileCanvas.boundingBox();
 assert(bounds.height>340,'mobile board too short '+bounds.height);
 await mp.screenshot({path:'final/evidence/08-gameplay-mobile.png',fullPage:true});
 await mobileCanvas.tap({position:{x:bounds.width*.48,y:bounds.height*.39}});
 assert.equal(await mp.evaluate(()=>window.YimmaQA.getState().screen),'game');
 assert.equal(await mp.evaluate(()=>window.YimmaQA.getState().types),23);
 assert.deepEqual(errors,[],errors.join('\n'));
 console.log('PASS MOBILE: 390x844, all world cards, touch canvas, 23 items, game renders');
 await mobile.close();
}finally{await browser.close()}
